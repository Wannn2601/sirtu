const modulSlice = createSlice({
  name: "modul",
  initialState,
  reducers: {
    addModule: (state, action) => {
      const newModule = { ...action.payload }

      // Find the highest existing ID and increment by 1
      const maxId = Math.max(...state.modules.map((m) => Number.parseInt(m.id_menu)))
      newModule.id_menu = String(maxId + 1)

      state.modules.push(newModule)
    },
    updateModule: (state, action) => {
      const index = state.modules.findIndex((m) => m.id_menu === action.payload.id_menu)
      if (index !== -1) {
        state.modules[index] = { ...state.modules[index], ...action.payload }
      }
    },
    deleteModule: (state, action) => {
      state.modules = state.modules.filter((m) => m.id_menu !== action.payload)
    },
    setLoading: (state, action) => {
      state.loading = action.payload
    },
    setError: (state, action) => {
      state.error = action.payload
    },
  },
})

export const { addModule, updateModule, deleteModule, setLoading, setError } = modulSlice.actions
export default modulSlice.reducer
